def get_random_ua() -> str:
    """返回一个随机 User-Agent"""
    return random.choice(_USER_AGENTS)


def get_academic_ua() -> str:
    """返回适合学术网站的 User-Agent（桌面 Chrome 优先）"""
    return random.choice(_ACADEMIC_PREFERRED_UAS)


def get_all_uas() -> list:
    """返回全部 User-Agent 列表（只读副本）"""
    return list(_USER_AGENTS)
